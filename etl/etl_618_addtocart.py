def classify(pid: str, name: str) -> str:
    """
    618 加购的分类规则（严格按 handoff/spec/分类逻辑规范.md 第 1 节）：
      1. 在映射表里 → 用映射表的一级（购物金 → __排除__）
      2. 不在映射表 → 看名字关键词
         - 空 / "-" / 含 "测试/展【/【积分兑换】/邮费" → __排除__
         - 含 "灯" → 灯具
         - 含 "抱枕/靠垫/坐垫/Cushion" → 配饰（spec 没覆盖的 edge case，
           Cushion 名字里常出现"沙发卧室抱枕"等描述用法，要先于 沙发/椅 拦截）
         - 含 "沙发/椅/茶几/桌" → 家具
         - 其他 → 配饰
    返回值：'家具' / '配饰' / '灯具' / '__排除__'
    """
    pid_s = str(pid).strip() if pid is not None else ""
    name_s = str(name).strip() if name is not None else ""
    if pid_s in MAPPING_TABLE:
        cat = MAPPING_TABLE[pid_s]
        return "__排除__" if cat == "购物金" else cat
    if not name_s or name_s == "-":
        return "__排除__"
    for kw in ("测试", "展【", "【积分兑换】", "邮费"):
        if kw in name_s:
            return "__排除__"
    if "灯" in name_s:
        return "灯具"
    if "抱枕" in name_s or "靠垫" in name_s or "坐垫" in name_s or "Cushion" in name_s:
        return "配饰"
    if "沙发" in name_s or "椅" in name_s or "茶几" in name_s or "桌" in name_s:
        return "家具"
    return "配饰"

